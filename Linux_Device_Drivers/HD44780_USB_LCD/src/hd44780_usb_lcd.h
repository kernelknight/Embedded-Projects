#ifndef HD44780_USB_LCD_H
#define HD44780_USB_LCD_H

#include <linux/ioctl.h>

#define HD44780_USB_IOC_MAGIC 'U'
#define HD44780_USB_IOC_CLEAR _IO(HD44780_USB_IOC_MAGIC, 0x01)
#define HD44780_USB_IOC_HOME _IO(HD44780_USB_IOC_MAGIC, 0x02)
#define HD44780_USB_IOC_DISPLAY_ON _IO(HD44780_USB_IOC_MAGIC, 0x03)
#define HD44780_USB_IOC_DISPLAY_OFF _IO(HD44780_USB_IOC_MAGIC, 0x04)

#define HD44780_CMD_CLEAR 0x01
#define HD44780_CMD_HOME 0x02
#define HD44780_CMD_ENTRY_MODE 0x06
#define HD44780_CMD_DISPLAY_ON 0x0c
#define HD44780_CMD_DISPLAY_OFF 0x08
#define HD44780_CMD_FUNCTION_4BIT_2LINE 0x28
#define HD44780_CMD_LINE1 0x80
#define HD44780_CMD_LINE2 0xc0

#endif
